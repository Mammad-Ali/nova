  /// Substitutes values into a template: `fill('{0} of {1}', ['2', '5'])`.
  static String fill(String template, List<String> args) {
    var out = template;
    for (var i = 0; i < args.length; i++) {
      out = out.replaceAll('{$i}', args[i]);
    }
    return out;
  }

