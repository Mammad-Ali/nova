import 'package:flutter/widgets.dart';

/// Languages the app supports.
enum AppLocale {
  en,
  az,
  ru,
  de,
  hu;

  Locale get locale => switch (this) {
        AppLocale.en => const Locale('en'),
        AppLocale.az => const Locale('az'),
        AppLocale.ru => const Locale('ru'),
        AppLocale.de => const Locale('de'),
        AppLocale.hu => const Locale('hu'),
      };

  /// The language's name in its own language, for the picker.
  String get nativeName => switch (this) {
        AppLocale.en => 'English',
        AppLocale.az => 'Azərbaycan',
        AppLocale.ru => 'Русский',
        AppLocale.de => 'Deutsch',
        AppLocale.hu => 'Magyar',
      };

  static AppLocale fromCode(String? code) => switch (code) {
        'en' => AppLocale.en,
        'az' => AppLocale.az,
        'ru' => AppLocale.ru,
        'de' => AppLocale.de,
        'hu' => AppLocale.hu,
        _ => AppLocale.ru,
      };
}

